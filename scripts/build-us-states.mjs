// Builds lib/us-states.ts — the lower-48 state shapes for the Get a Quote map.
// Source: us-atlas states-10m (US Census Bureau cartographic boundaries, public domain).
// The tools aren't project dependencies; to re-run from the repo root:
//   npm i --no-save us-atlas@3 topojson-client@3 topojson-simplify@3 d3-geo@3
//   node scripts/build-us-states.mjs
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoAlbers, geoPath } from "d3-geo";
import { feature } from "topojson-client";
import { presimplify, quantile, simplify } from "topojson-simplify";

const require = createRequire(import.meta.url);
const topology = require("us-atlas/states-10m.json");

const WIDTH = 960;
const PADDING = 8;
/** Share of the smallest border points dropped — keeps the file small without visible loss at map size. */
const SIMPLIFY = 0.6;

const codes = {
  Alabama: "AL", Arizona: "AZ", Arkansas: "AR", California: "CA", Colorado: "CO", Connecticut: "CT",
  Delaware: "DE", "District of Columbia": "DC", Florida: "FL", Georgia: "GA", Idaho: "ID", Illinois: "IL",
  Indiana: "IN", Iowa: "IA", Kansas: "KS", Kentucky: "KY", Louisiana: "LA", Maine: "ME", Maryland: "MD",
  Massachusetts: "MA", Michigan: "MI", Minnesota: "MN", Mississippi: "MS", Missouri: "MO", Montana: "MT",
  Nebraska: "NE", Nevada: "NV", "New Hampshire": "NH", "New Jersey": "NJ", "New Mexico": "NM",
  "New York": "NY", "North Carolina": "NC", "North Dakota": "ND", Ohio: "OH", Oklahoma: "OK", Oregon: "OR",
  Pennsylvania: "PA", "Rhode Island": "RI", "South Carolina": "SC", "South Dakota": "SD", Tennessee: "TN",
  Texas: "TX", Utah: "UT", Vermont: "VT", Virginia: "VA", Washington: "WA", "West Virginia": "WV",
  Wisconsin: "WI", Wyoming: "WY",
};
const names = { "District of Columbia": "Washington, D.C." };

const simplified = simplify(presimplify(topology), quantile(presimplify(topology), SIMPLIFY));
const all = feature(simplified, simplified.objects.states);
// Alaska, Hawaii and the territories aren't in `codes`, so they drop out here.
const lower48 = { type: "FeatureCollection", features: all.features.filter((f) => codes[f.properties.name]) };

const projection = geoAlbers().fitWidth(WIDTH - PADDING * 2, lower48);
const [[x0, y0], [, y1]] = geoPath(projection).bounds(lower48);
const [tx, ty] = projection.translate();
projection.translate([tx + PADDING - x0, ty + PADDING - y0]);
const height = Math.ceil(y1 - y0 + PADDING * 2);
const path = geoPath(projection).digits(1);

/** Label/pin spot: the centroid of the state's largest piece (so Michigan's pin lands on the mitten, not the lake). */
function anchor(f) {
  const pieces =
    f.geometry.type === "MultiPolygon"
      ? f.geometry.coordinates.map((coordinates) => ({ type: "Polygon", coordinates }))
      : [f.geometry];
  const largest = pieces.reduce((a, b) => (path.area(b) > path.area(a) ? b : a));
  return path.centroid(largest).map((n) => Math.round(n * 10) / 10);
}

const states = lower48.features
  .map((f) => {
    const [cx, cy] = anchor(f);
    const name = names[f.properties.name] ?? f.properties.name;
    return { code: codes[f.properties.name], name, d: path(f), cx, cy };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

const out = `// Generated by scripts/build-us-states.mjs — don't edit by hand.
// Lower 48 states + Washington, D.C. (Alaska and Hawaii left out: we don't run there).
// Shapes: US Census Bureau via us-atlas (public domain), Albers projection.

export type StateCode = ${states.map((s) => JSON.stringify(s.code)).join(" | ")};

export type UsState = {
  code: StateCode;
  name: string;
  /** SVG path in map units. */
  d: string;
  /** Pin spot in map units. */
  cx: number;
  cy: number;
};

export const US_MAP_WIDTH = ${WIDTH};
export const US_MAP_HEIGHT = ${height};

/** Sorted by name, ready for a state dropdown. */
export const usStates: UsState[] = ${JSON.stringify(states, null, 2)};
`;

writeFileSync(new URL("../lib/us-states.ts", import.meta.url), out);
console.log(`lib/us-states.ts: ${states.length} states, ${WIDTH}×${height}, ${(out.length / 1024).toFixed(1)} KB`);
